# No telemetry here on purpose: by the repository contract telemetry is headers on
# requests a skill was making anyway, and this one makes none.


class _Parser(argparse.ArgumentParser):
    """Usage errors exit 3, so that 2 always means «the plan has errors»."""

    def error(self, message: str) -> "None":  # type: ignore[override]
        self.print_usage(sys.stderr)
        print(f"{self.prog}: error: {message}", file=sys.stderr)
        raise SystemExit(EXIT_USAGE)


# --- doctor ----------------------------------------------------------------------------


def cmd_doctor(_args: argparse.Namespace) -> int:
    docs = catalog.all_widget_docs()
    recipes = catalog.all_recipes()
    presets = sum(len(doc.get("presets", [])) for doc in docs)
    print(f"presets : {presets} across {len(docs)} widgets (incl. theme)")
    by_type: "dict[str, int]" = {}
    for recipe in recipes:
        by_type[str(recipe.get("page_type"))] = by_type.get(str(recipe.get("page_type")), 0) + 1
    print(f"recipes : {len(recipes)} ({', '.join(f'{k} {v}' for k, v in by_type.items())})")
    print(f"rules   : {len(lint.RULES)} plan-lint rules")
    errors = catalog.consistency_errors()
    for error in errors:
        print(f"  inconsistent: {error}", file=sys.stderr)
    print("state   : " + ("consistent" if not errors else f"{len(errors)} problem(s)"))
    return EXIT_FINDINGS if errors else EXIT_OK


