def recipes_markdown(recipes: "list[dict[str, object]]") -> str:
    """references/recipes/INDEX.md: generated by `design.py recipes list --markdown`."""
    lines = [
        "# Recipes",
        "",
        "Generated by `scripts/design.py recipes list --markdown`; do not edit by hand.",
        "Read one with `design.py recipes show <id>`; get a plan skeleton with `--plan`.",
        "An *optional idea* rests on fewer than 3 stores of the sample: use it when the user asks for that look, never as a default.",
        "",
        "| Recipe | Page | What it is for | Evidence |",
        "|---|---|---|---|",
    ]
    for recipe in recipes:
        idea = " *(optional idea)*" if catalog.is_idea(recipe) else ""
        lines.append(f"| `{recipe['id']}` | {recipe['page_type']} | {recipe['title']} | {recipe['evidence']}{idea} |")
    return "\n".join(lines)


def step_options(step: "dict[str, object]") -> "list[dict[str, object]]":
    """A slot's interchangeable options: the step itself first, then its `variants`."""
    first = {key: step[key] for key in ("widget", "preset", "pattern") if step.get(key)}
    first["when"] = step.get("when") or "the sample's most common choice for this slot"
    options = [first]
    for option in step.get("variants") or []:  # type: ignore[union-attr]
        options.append({key: option[key] for key in ("widget", "preset", "pattern", "role", "when", "idea") if key in option})
    return options


def recipe_plan(recipe: "dict[str, object]", with_optional: bool) -> "dict[str, object]":
    """The plan skeleton: a slot with options is left as a `choose` list, never filled with the first."""
    sections = []
    for step in recipe.get("steps", []):  # type: ignore[union-attr]
        if step.get("optional") and not with_optional:
            continue
        if step.get("variants"):
            entry = {"slot": step["slot"], "role": step.get("role"), "choose": step_options(step)}
        else:
            entry = {key: step[key] for key in ("widget", "preset", "role", "pattern") if step.get(key)}
        if step.get("optional"):
            entry["optional"] = True
        if step.get("note"):
            entry["note"] = step["note"]
        sections.append(entry)
    plan: "dict[str, object]" = {
        "page": recipe.get("page_alias") or recipe.get("page_type"),
        "page_type": recipe.get("page_type"),
        "recipe": recipe.get("id"),
        "stage": "draft",
    }
    if recipe.get("page_type") == "home":
        plan["look"] = "<fill: a look from references/looks.md and the 2-3 moves that set this store apart>"
    plan["theme"] = recipe.get("theme", [])
    plan["sections"] = sections
    return plan


def _option_label(option: "dict[str, object]") -> str:
    preset = f" · {option['preset']}" if option.get("preset") else ""
    pattern = f" · custom pattern {option['pattern']}" if option.get("pattern") else ""
    idea = " (optional idea)" if option.get("idea") else ""
    return f"{catalog.short_name(str(option['widget']))}{preset}{pattern}{idea}"


def cmd_recipes_show(args: argparse.Namespace) -> int:
    recipe = catalog.find_recipe(args.id)
    if args.plan:
        print(dump_json(recipe_plan(recipe, args.with_optional)))
        return EXIT_OK
    if args.json:
        print(dump_json(recipe))
        return EXIT_OK
    print(f"{recipe['id']} — {recipe['title']}")
    print(f"page: {recipe['page_type']}" + (f" (alias {recipe['page_alias']})" if recipe.get("page_alias") else ""))
    print(f"evidence: {recipe['evidence']}" + ("  — an optional idea, not a default" if catalog.is_idea(recipe) else ""))
    if recipe.get("when"):
        print(f"when: {recipe['when']}")
    if recipe.get("theme"):
        print("theme first: " + ", ".join(f"theme/{name}" for name in recipe["theme"]))  # type: ignore[union-attr]
    print("sections (a slot with options: choose by the brief and the look, references/looks.md):")
    for number, step in enumerate(recipe.get("steps", []), start=1):  # type: ignore[arg-type]
        optional = " (optional)" if step.get("optional") else ""
        options = step_options(step)
        if len(options) > 1:
            print(f"  {number:>2}. slot {step['slot']} [{step.get('role', '-')}]{optional}, choose one:")
            for letter, option in zip("abcdefgh", options):
                print(f"      {letter}) {_option_label(option)} — {option['when']}")
        else:
            print(f"  {number:>2}. {_option_label(options[0])} [{step.get('role', '-')}]{optional}")
        if step.get("note"):
            print(f"      {step['note']}")
    for note in recipe.get("notes", []):  # type: ignore[union-attr]
        print(f"note: {note}")
    return EXIT_OK


