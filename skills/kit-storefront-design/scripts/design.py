#!/usr/bin/env python3
"""kit-storefront-design — design Яндекс.Кит storefront pages from native sections, offline.

The single entry point of the skill. Python 3.9+, standard library only. No network
and no token: it reads recipes and presets shipped with the skill, merges presets
over settings the constructor gave you, and lints page plans. Every write to the
store is a `kit-storefront-constructor` command; custom sections are built by
`kit-custom-sections`.

    design.py doctor
    design.py recipes list [--page-type home]
    design.py recipes show home-fashion [--plan [--with-optional]]
    design.py presets list [WIDGET]
    design.py presets show WIDGET [PRESET]
    design.py presets apply WIDGET PRESET (--base FILE | --work FILE [--section-id UUID]) [--schema FILE [--as-new]] [--restyle-modules] --out FILE
    design.py plan lint plan.json [--final] [--strict] [--json]
    design.py plan lint --work work.json (--page main ... [--page-type T] | --all-pages) [--strict] [--json]
    design.py plan rules
    design.py theme palettes --work work.json [--prune --out gs.json] [--json]
    design.py media-object (--upload upload.json [--kind image|banner] | --video-status status.json)

Exit codes: 0 ok (warnings allowed); 2 the plan has errors, or warnings under --strict,
or the references are inconsistent; 3 usage; 5 recipe, preset or page not found.
"""

from __future__ import annotations

