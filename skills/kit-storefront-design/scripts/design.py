def video_object(status: object) -> "dict[str, object]":
    """`kit.py media video-status` output (once `ready`) → the media object a video slide stores.

    The shape is the one live video slides carry: `fileId` is the video id, `filePath` the
    first frame, `type` VIDEO, plus the stream links the storefront plays."""
    if not isinstance(status, dict) or not isinstance(status.get("id"), str) or not status["id"]:
        raise DesignError("This is not `kit.py media video-status` output: it needs `id`, `status` and `content`.")
    if status.get("status") != "ready":
        raise DesignError(f"The video is {status.get('status')!r}, not ready: poll `kit.py … media video-status --id {status['id']}` until it is.")
    content = status.get("content") if isinstance(status.get("content"), dict) else {}
    frame = content.get("first_frame_url")  # type: ignore[union-attr]
    if not isinstance(frame, str) or not frame:
        raise DesignError("The ready video has no first_frame_url; the slide needs it as its poster.")
    media: "dict[str, object]" = {"fileId": status["id"], "filePath": frame, "type": "VIDEO", "sizes": [], "video_id": status["id"], "first_frame_url": frame}
    for key in ("stream_hls_url", "stream_dash_url"):
        if isinstance(content.get(key), str) and content.get(key):  # type: ignore[union-attr]
            media[key] = content[key]  # type: ignore[index]
    media["status"] = "ready"
    if isinstance(status.get("title"), str):
        media["title"] = status["title"]
    return media


def cmd_media_object(args: argparse.Namespace) -> int:
    """Turn `kit.py media upload` output into the image object section settings expect."""
    if args.video_status:
        print(dump_json(video_object(read_json(args.video_status))))
        return EXIT_OK
    if not args.upload:
        raise DesignError("Give --upload (image upload output) or --video-status (video status output).")
    uploaded = read_json(args.upload)
    if not isinstance(uploaded, dict):
        raise DesignError("The upload output must be a JSON object.")
    file_id, public_path = uploaded.get("id"), uploaded.get("public_path") or uploaded.get("url")
    if not isinstance(file_id, str) or not file_id or not isinstance(public_path, str) or not public_path:
        raise DesignError("This is not `kit.py media upload` output: it needs `id` and `public_path`.")
    if uploaded.get("type") not in (None, "IMAGE"):
        raise DesignError("Only image uploads map to an image object; for a video use --video-status with `kit.py media video-status` output.")
    sizes = uploaded.get("sizes") if isinstance(uploaded.get("sizes"), list) else []
    media: "dict[str, object]" = {"fileId": file_id, "filePath": public_path}
    if args.kind == "banner":
        media["type"] = "IMAGE"
    media["sizes"] = sizes
    print(dump_json(media))
    return EXIT_OK


# --- parser ----------------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = _Parser(prog="design.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True, parser_class=_Parser)

    doctor = sub.add_parser("doctor", help="Counts and internal consistency of the shipped references.")
    doctor.set_defaults(handler=cmd_doctor)

    recipes = sub.add_parser("recipes", help="Page recipes by page type and niche.")
    recipes_sub = recipes.add_subparsers(dest="recipes_command", required=True, parser_class=_Parser)
    r_list = recipes_sub.add_parser("list")
    r_list.add_argument("--page-type", choices=catalog.PAGE_TYPES)
    r_list.add_argument("--json", action="store_true")
    r_list.add_argument("--markdown", action="store_true", help="The INDEX.md table.")
    r_list.set_defaults(handler=cmd_recipes_list)
    r_show = recipes_sub.add_parser("show")
    r_show.add_argument("id")
    r_show.add_argument("--plan", action="store_true", help="Print a plan skeleton for `plan lint`.")
    r_show.add_argument("--with-optional", action="store_true", help="Include optional steps in --plan.")
    r_show.add_argument("--json", action="store_true")
    r_show.set_defaults(handler=cmd_recipes_show)

    presets = sub.add_parser("presets", help="Partial settings per native widget and for the theme.")
    presets_sub = presets.add_subparsers(dest="presets_command", required=True, parser_class=_Parser)
    p_list = presets_sub.add_parser("list")
    p_list.add_argument("widget", nargs="?")
    p_list.add_argument("--json", action="store_true")
    p_list.add_argument("--markdown", action="store_true", help="The INDEX.md table.")
    p_list.set_defaults(handler=cmd_presets_list)
    p_show = presets_sub.add_parser("show")
    p_show.add_argument("widget")
    p_show.add_argument("preset", nargs="?")
    p_show.set_defaults(handler=cmd_presets_show)
    p_apply = presets_sub.add_parser("apply", help="Merge a preset over a base and write settings for kit.py.")
    p_apply.add_argument("widget")
    p_apply.add_argument("preset")
    p_apply.add_argument("--base", help="kit.py schema widget --skeleton output, kit.py section show output, or plain settings.")
    p_apply.add_argument("--work", help="Constructor workspace (theme presets, or with --section-id).")
    p_apply.add_argument("--section-id", help="Section UUID inside --work.")
    p_apply.add_argument(
        "--schema",
        help="`kit.py … schema widget --name <widget> --skeleton` output of this store: the Header's modules.main shape when the "
        "section shows none, and platform copy (a consent text) for objects the preset creates, where the skeleton shows it.",
    )
    p_apply.add_argument(
        "--as-new",
        action="store_true",
        help="Build settings for a new section (`section add` on another page) from the pulled one: its settings over the --schema "
        "skeleton, without `version` and without the cabinet's empty-string paddings, which a new section may not carry.",
    )
    p_apply.add_argument(
        "--restyle-modules",
        action="store_true",
        help="Let the preset's module_style overwrite the style of slides and tiles that already carry content "
        "(by default they keep their own, and the report lists what was kept).",
    )
    p_apply.add_argument("--out", required=True, help="Where to write the merged settings.")
    p_apply.set_defaults(handler=cmd_presets_apply)

    plan = sub.add_parser("plan", help="Lint a page plan or a pulled page against the design principles.")
    plan_sub = plan.add_subparsers(dest="plan_command", required=True, parser_class=_Parser)
    l_lint = plan_sub.add_parser("lint")
    l_lint.add_argument("plan", nargs="?")
    l_lint.add_argument("--work", help="Lint pages of a constructor workspace instead of a plan file.")
    l_lint.add_argument("--page", action="append", help="Page alias, id or pattern inside --work (repeatable).")
    l_lint.add_argument("--all-pages", action="store_true")
    l_lint.add_argument(
        "--page-type",
        choices=catalog.PAGE_TYPES,
        help="Lint the page as this type (one --page): a custom page whose address does not tell what it is (/about, /faq, /promo… are recognised).",
    )
    l_lint.add_argument("--final", action="store_true", help="Treat the plan as ready to publish: markers and missing media are errors.")
    l_lint.add_argument("--strict", action="store_true", help="Warnings fail too (exit 2).")
    l_lint.add_argument("--json", action="store_true")
    l_lint.set_defaults(handler=cmd_plan_lint)
    l_rules = plan_sub.add_parser("rules")
    l_rules.add_argument("--json", action="store_true")
    l_rules.set_defaults(handler=cmd_plan_rules)

    theme = sub.add_parser("theme", help="Read the theme of a workspace.")
    theme_sub = theme.add_subparsers(dest="theme_command", required=True, parser_class=_Parser)
    t_pal = theme_sub.add_parser("palettes", help="Theme palettes: colours, contrast, role and how many sections use each.")
    t_pal.add_argument("--work", required=True, help="Constructor workspace (`kit.py … content pull --out`).")
    t_pal.add_argument("--prune", action="store_true", help="Write global_settings without the palettes no section uses (the base one stays).")
    t_pal.add_argument("--out", help="Where --prune writes global_settings for `kit.py … theme set --settings-file`.")
    t_pal.add_argument("--json", action="store_true")
    t_pal.set_defaults(handler=cmd_theme_palettes)

    media = sub.add_parser("media-object", help="Media object for section settings from `kit.py media upload` or `media video-status` output.")
    media.add_argument("--upload", help="File with the image upload output, or - for stdin.")
    media.add_argument("--video-status", help="File with `kit.py media video-status` output of a ready video, or - for stdin.")
    media.add_argument("--kind", choices=("image", "banner"), default="image", help="banner adds type IMAGE for slide media.")
    media.set_defaults(handler=cmd_media_object)
    return parser


def main(argv: "list[str] | None" = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.handler(args)
    except DesignError as error:
        print(f"design.py: {error}", file=sys.stderr)
        return error.code


if __name__ == "__main__":
    raise SystemExit(main())
